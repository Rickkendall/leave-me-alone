// Generates the declarativeNetRequest static rulesets in extension/rules/.
// Usage: node tools/build-rules.mjs
import { writeFileSync } from "node:fs";
import { TRACKERS, STRICT_EXTRA, TRACKING_PARAMS } from "./lists.mjs";

const OUT = new URL("../extension/rules/", import.meta.url);
const SUB = ["sub_frame", "stylesheet", "script", "image", "font", "object", "xmlhttprequest",
  "ping", "csp_report", "media", "websocket", "webtransport", "webbundle", "other"];

const uniq = (a) => [...new Set(a.map((d) => d.toLowerCase().trim()))];

function blockRules(list, startId) {
  const domains = uniq(list).filter((d) => !d.includes("/"));
  const paths = uniq(list).filter((d) => d.includes("/"));
  const rules = [{
    id: startId, priority: 1, action: { type: "block" },
    condition: { requestDomains: domains, domainType: "thirdParty", resourceTypes: SUB },
  }];
  paths.forEach((p, i) => rules.push({
    id: startId + 1 + i, priority: 1, action: { type: "block" },
    condition: { urlFilter: `||${p}`, domainType: "thirdParty", resourceTypes: SUB },
  }));
  return rules;
}

const write = (name, rules) => {
  writeFileSync(new URL(name, OUT), JSON.stringify(rules, null, 1) + "\n");
  console.log(`${name}: ${rules.length} rules`);
};

// Shared with the in-page link cleaner.
writeFileSync(new URL("../src/params.js", OUT),
  `// Generated by tools/build-rules.mjs — do not edit.\nvar LMA_TRACKING_PARAMS = ${JSON.stringify(uniq(TRACKING_PARAMS))};\n`);

// Mild ----------------------------------------------------------------------
write("trackers.json", blockRules(TRACKERS, 1));

const params = uniq(TRACKING_PARAMS);
// Only fire when the exact param is present (anchored on ? or &, case-sensitive like
// removeParams), so a rule can never redirect a URL to itself.
write("params.json", params.flatMap((p) => ["?", "&"].map((sep) => `${sep}${p}=`)).map((f, i) => ({
  id: i + 1, priority: 1,
  action: { type: "redirect", redirect: { transform: { queryTransform: { removeParams: params } } } },
  condition: { urlFilter: f, isUrlFilterCaseSensitive: true, resourceTypes: ["main_frame", "sub_frame"] },
})));

// Two rules: page loads are scoped to the site being visited, everything else to the
// page that made the request (see siteScope() in background.js).
const signalHeaders = { type: "modifyHeaders", requestHeaders: [
  { header: "Sec-GPC", operation: "set", value: "1" },
  { header: "DNT", operation: "set", value: "1" },
] };
write("signals.json", [
  { id: 1, priority: 1, action: signalHeaders, condition: { resourceTypes: ["main_frame"] } },
  { id: 2, priority: 1, action: signalHeaders, condition: { resourceTypes: SUB } },
]);

// Balanced --------------------------------------------------------------------
write("balanced.json", [
  { id: 1, priority: 1,
    action: { type: "modifyHeaders",
      requestHeaders: [{ header: "cookie", operation: "remove" }, { header: "referer", operation: "remove" }],
      responseHeaders: [{ header: "set-cookie", operation: "remove" }] },
    condition: { domainType: "thirdParty", resourceTypes: SUB } },
  { id: 2, priority: 1, action: { type: "block" },
    condition: { domainType: "thirdParty", resourceTypes: ["ping", "csp_report"] } },
]);

// Strict ----------------------------------------------------------------------
write("strict.json", blockRules(STRICT_EXTRA, 1));

// Paranoid --------------------------------------------------------------------
write("paranoid.json", [
  // No third-party iframes or sockets at all (embeds, chat widgets, ad frames).
  { id: 1, priority: 1, action: { type: "block" },
    condition: { domainType: "thirdParty", resourceTypes: ["sub_frame", "websocket", "webtransport", "object"] } },
  // Kill ETag/cache-based supercookies on third-party requests.
  { id: 2, priority: 1,
    action: { type: "modifyHeaders",
      requestHeaders: [{ header: "if-none-match", operation: "remove" }, { header: "if-modified-since", operation: "remove" }],
      responseHeaders: [{ header: "etag", operation: "remove" }, { header: "last-modified", operation: "remove" }] },
    condition: { domainType: "thirdParty", resourceTypes: SUB } },
  // Never tell the next site where you came from.
  { id: 3, priority: 1,
    action: { type: "modifyHeaders", requestHeaders: [{ header: "referer", operation: "remove" }] },
    condition: { resourceTypes: ["main_frame"] } },
]);
